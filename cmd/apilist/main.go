// Command apilist regenerates api.txt, the golden file CHARTER.md requires:
// this module's public surface, written down so that growing it is a reviewed
// diff rather than something that happens quietly. `mise run api` writes it;
// `mise run api-check` writes it and fails if the result differs from what is
// committed.
//
// It lists every exported declaration of every package in the module except
// main packages — internal/domain included. That is deliberate: every
// declaration in internal/domain is reachable through a type alias in the
// root keyring package, so a new exported method on domain.DEK is a new
// public method on keyring.DEK whether or not the facade mentions it. If a
// future internal package is genuinely unreachable from the facade, this
// rule is the thing to change, and changing it is itself a reviewed diff.
//
// It parses source rather than type-checking it, so what it prints is what
// the declaration says — an alias stays an alias, and a constant's
// expression is shown as written.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// outputName is the golden file this command writes, at the module root.
const outputName = "api.txt"

func main() {
	log.SetFlags(0)
	if err := run(); err != nil {
		log.Fatalf("apilist: %v", err)
	}
}

func run() error {
	root, modulePath, err := moduleRoot()
	if err != nil {
		return err
	}

	dirs, err := packageDirs(root)
	if err != nil {
		return err
	}

	var out bytes.Buffer
	out.WriteString("# Public API of " + modulePath + "\n")
	out.WriteString("# Generated by `mise run api` (cmd/apilist). Do not edit by hand.\n")
	for _, dir := range dirs {
		section, err := packageSection(root, modulePath, dir)
		if err != nil {
			return err
		}
		out.WriteString(section)
	}

	path := filepath.Join(root, outputName)
	if err := os.WriteFile(path, out.Bytes(), 0o644); err != nil { //nolint:gosec // a golden file in the repository is world-readable by design
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

// moduleRoot walks up from the working directory to the directory holding
// go.mod, and returns it along with the module path declared there.
func moduleRoot() (root, modulePath string, err error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", "", fmt.Errorf("working directory: %w", err)
	}
	for {
		gomod := filepath.Join(dir, "go.mod")
		// G304 is expected: the path is this repository's own go.mod, found
		// by walking up from the working directory, and this is a developer
		// tool run by `mise run api` rather than anything that serves a
		// request.
		contents, readErr := os.ReadFile(gomod) //nolint:gosec
		if readErr == nil {
			path, ok := modulePathFrom(contents)
			if !ok {
				return "", "", fmt.Errorf("%s has no module declaration", gomod)
			}
			return dir, path, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", "", errors.New("no go.mod found in any parent directory")
		}
		dir = parent
	}
}

// modulePathFrom extracts the module path from go.mod's contents.
func modulePathFrom(contents []byte) (string, bool) {
	for line := range strings.Lines(string(contents)) {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.TrimSpace(rest), true
		}
	}
	return "", false
}

// packageDirs returns every directory under root holding non-test Go files,
// relative to root and sorted, skipping the ones no consumer can reach:
// dotted directories, testdata, and (further down) main packages.
func packageDirs(root string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			name := d.Name()
			if path != root && (strings.HasPrefix(name, ".") || name == "testdata") {
				return fs.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(d.Name(), ".go") || strings.HasSuffix(d.Name(), "_test.go") {
			return nil
		}
		rel, relErr := filepath.Rel(root, filepath.Dir(path))
		if relErr != nil {
			return relErr
		}
		if !slices.Contains(dirs, rel) {
			dirs = append(dirs, rel)
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("walk %s: %w", root, err)
	}
	slices.Sort(dirs)
	return dirs, nil
}

// packageSection renders one package's exported surface, or the empty string
// for a main package (a command is not API).
func packageSection(root, modulePath, dir string) (string, error) {
	absolute := filepath.Join(root, dir)
	entries, err := os.ReadDir(absolute)
	if err != nil {
		return "", fmt.Errorf("read %s: %w", dir, err)
	}

	fset := token.NewFileSet()
	var lines []string
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, parseErr := parser.ParseFile(fset, filepath.Join(absolute, name), nil, parser.SkipObjectResolution)
		if parseErr != nil {
			return "", fmt.Errorf("parse %s: %w", filepath.Join(dir, name), parseErr)
		}
		if file.Name.Name == "main" {
			continue
		}
		lines = append(lines, declarations(fset, file)...)
	}
	if len(lines) == 0 {
		return "", nil
	}

	// Sort with the kind prefix in place, then strip it: the prefix exists
	// only to group kinds, and must not reach the golden file.
	slices.Sort(lines)
	for i, line := range lines {
		if _, rest, ok := strings.Cut(line, "\x00"); ok {
			lines[i] = rest
		}
	}

	importPath := modulePath
	if dir != "." {
		importPath += "/" + filepath.ToSlash(dir)
	}
	return "\n# " + importPath + "\n" + strings.Join(lines, "\n") + "\n", nil
}

// declarations renders every exported declaration in one file as an entry
// each, prefixed with a sort key so that constants, variables, types,
// methods and functions group together in a stable order regardless of which
// file they were declared in.
func declarations(fset *token.FileSet, file *ast.File) []string {
	var lines []string
	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			lines = append(lines, genDeclLines(fset, d)...)
		case *ast.FuncDecl:
			if line, ok := funcLine(fset, d); ok {
				lines = append(lines, line)
			}
		}
	}
	return lines
}

// genDeclLines renders the exported specs of one const, var or type
// declaration, one entry per spec so that a grouped declaration and a set of
// single ones produce the same output.
func genDeclLines(fset *token.FileSet, decl *ast.GenDecl) []string {
	var lines []string
	for _, spec := range decl.Specs {
		switch s := spec.(type) {
		case *ast.ValueSpec:
			for i, name := range s.Names {
				if !name.IsExported() {
					continue
				}
				lines = append(lines, valueLine(fset, decl.Tok, name, s, i))
			}
		case *ast.TypeSpec:
			if !s.Name.IsExported() {
				continue
			}
			lines = append(lines, sortKey(decl.Tok.String())+typeLine(fset, s))
		}
	}
	return lines
}

// valueLine renders one exported constant or variable with both its type,
// when it is written down, and its value expression, when there is one: both
// halves are things a consumer can observe, and a change to either is a
// change to the surface.
func valueLine(fset *token.FileSet, tok token.Token, name *ast.Ident, spec *ast.ValueSpec, i int) string {
	line := tok.String() + " " + name.Name
	if spec.Type != nil {
		line += " " + render(fset, spec.Type)
	}
	if i < len(spec.Values) {
		line += " = " + render(fset, spec.Values[i])
	}
	return sortKey(tok.String()) + line
}

// typeLine renders one exported type declaration. A struct is rendered field
// by field, keeping only the exported ones and saying so when others exist,
// because an unexported field is not API and reordering or renaming one must
// not show up as an API change. Everything else — an alias, a defined
// string, an interface — is printed as written.
func typeLine(fset *token.FileSet, spec *ast.TypeSpec) string {
	structType, ok := spec.Type.(*ast.StructType)
	if !ok {
		return render(fset, stripComments(&ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{spec}}))
	}

	head := "type " + spec.Name.Name + " struct {"
	var fields []string
	hidden := false
	for _, field := range structType.Fields.List {
		if len(field.Names) == 0 { // an embedded type
			fields = append(fields, "\t"+render(fset, field.Type))
			continue
		}
		var names []string
		for _, name := range field.Names {
			if name.IsExported() {
				names = append(names, name.Name)
			} else {
				hidden = true
			}
		}
		if len(names) > 0 {
			fields = append(fields, "\t"+strings.Join(names, ", ")+" "+render(fset, field.Type))
		}
	}
	if hidden {
		fields = append(fields, "\t// has unexported fields")
	}
	if len(fields) == 0 {
		return head + "}"
	}
	return head + "\n" + strings.Join(fields, "\n") + "\n}"
}

// funcLine renders one exported function or method signature, body removed.
// A method on an unexported type is not API and is skipped.
func funcLine(fset *token.FileSet, decl *ast.FuncDecl) (string, bool) {
	if !decl.Name.IsExported() {
		return "", false
	}
	kind := "func"
	if decl.Recv != nil {
		if !exportedReceiver(decl.Recv) {
			return "", false
		}
		kind = "method"
	}
	signature := &ast.FuncDecl{
		Recv: decl.Recv,
		Name: decl.Name,
		Type: decl.Type,
	}
	return sortKey(kind) + render(fset, stripComments(signature)), true
}

// exportedReceiver reports whether a method's receiver type is exported, for
// both value and pointer receivers.
func exportedReceiver(recv *ast.FieldList) bool {
	if len(recv.List) == 0 {
		return false
	}
	expr := recv.List[0].Type
	if star, ok := expr.(*ast.StarExpr); ok {
		expr = star.X
	}
	ident, ok := expr.(*ast.Ident)
	return ok && ident.IsExported()
}

// sortKey prefixes an entry so that `slices.Sort` groups kinds in a fixed
// order. packageSection strips the prefix after sorting; the separator is a
// null byte, which no Go signature contains.
func sortKey(kind string) string {
	order := map[string]string{"const": "1", "var": "2", "type": "3", "method": "4", "func": "5"}
	key, ok := order[kind]
	if !ok {
		key = "9"
	}
	return key + "\x00"
}

// render prints one AST node on a single logical entry, with comments
// stripped and blank lines collapsed, so that reformatting a doc comment
// never shows up as an API change.
func render(fset *token.FileSet, node ast.Node) string {
	var buf bytes.Buffer
	cfg := printer.Config{Mode: printer.RawFormat, Tabwidth: 4}
	if err := cfg.Fprint(&buf, fset, node); err != nil {
		// A node that came out of the parser cannot fail to print; returning
		// the error's text keeps this total rather than fatal.
		return "<unprintable: " + err.Error() + ">"
	}
	var kept []string
	for line := range strings.Lines(buf.String()) {
		trimmed := strings.TrimRight(line, "\n")
		if strings.TrimSpace(trimmed) == "" {
			continue
		}
		kept = append(kept, trimmed)
	}
	return strings.Join(kept, "\n")
}

// stripComments clears the doc and line comments of a node and everything
// under it, so that printing a declaration yields its signature and nothing
// else.
func stripComments(node ast.Node) ast.Node {
	ast.Inspect(node, func(n ast.Node) bool {
		switch v := n.(type) {
		case *ast.Field:
			v.Doc, v.Comment = nil, nil
		case *ast.ValueSpec:
			v.Doc, v.Comment = nil, nil
		case *ast.TypeSpec:
			v.Doc, v.Comment = nil, nil
		case *ast.FuncDecl:
			v.Doc = nil
		case *ast.GenDecl:
			v.Doc = nil
		}
		return true
	})
	return node
}
